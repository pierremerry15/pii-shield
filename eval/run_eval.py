"""Compare the three scrubbers on the dev and test splits.

python -m eval.run_eval            # print tables, write eval/RESULTS.md + results.json
python -m eval.run_eval --chart    # also write docs/eval_chart.png (needs matplotlib)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from baselines.pathreview_original import PIIScrubber as Original
from baselines.pathreview_pr98 import PIIScrubber as PR98
from eval.dataset import TYPES, is_test_split_frozen, load_split
from eval.metrics import Report, evaluate
from pii_shield import PIIScrubber as V2

ROOT = Path(__file__).resolve().parent.parent
ENGINES = (
    ("original", "PathReview original", Original),
    ("pr98", "PathReview + PR #98", PR98),
    ("v2", "PII Shield v2", V2),
)


def pct(x: float) -> str:
    return "—" if x != x else f"{100 * x:.0f}%"  # x != x is NaN


def table(reports: list[Report], n_examples: int) -> str:
    head = "| Metric | " + " | ".join(r.name for r in reports) + " |"
    sep = "|---|" + "---:|" * len(reports)
    rows = [head, sep]
    rows.append("| **Recall** (PII fully hidden) | " + " | ".join(pct(r.recall) for r in reports) + " |")
    for t in TYPES:
        gold = reports[0].by_type[t]["gold"]
        rows.append(
            f"| &nbsp;&nbsp;{t} ({gold}) | " + " | ".join(f"{r.by_type[t]['protected']}/{gold}" for r in reports) + " |"
        )
    rows.append("| Partial leaks | " + " | ".join(str(r.totals()["partial"]) for r in reports) + " |")
    rows.append("| **Precision** (redactions that were PII) | " + " | ".join(pct(r.precision) for r in reports) + " |")
    rows.append(
        f"| **Clean negatives** ({reports[0].negatives} lines with no PII) | "
        + " | ".join(f"{r.negatives_clean}/{r.negatives}" for r in reports)
        + " |"
    )
    rows.append("| **F1** | " + " | ".join(f"{r.f1:.2f}" for r in reports) + " |")
    return "\n".join(rows) + f"\n\n_{n_examples} examples._"


def failures_md(report: Report, split: str) -> str:
    if not report.failures:
        return f"- **{report.name}**: none\n"
    lines = [f"- **{report.name}** ({len(report.failures)}):"]
    for f in report.failures:
        lines.append(f"  - `{split}.txt` line {f.line_no}: {f.kind.replace('_', ' ')}, {f.detail}")
    return "\n".join(lines) + "\n"


def run(chart: bool = False) -> dict:
    if not is_test_split_frozen():
        sys.exit("eval/data/test.txt has changed since it was frozen. Refusing to report test numbers.")

    results: dict = {}
    md = [
        "# Evaluation results",
        "",
        "Generated by `python -m eval.run_eval`. Do not edit by hand.",
        "",
        "Recall counts a PII value as protected only if **every** character is hidden.",
        "A partial leak (for example `+44` hidden but `20 7946 0958` left in the text) counts as a miss.",
        "",
    ]
    titles = {
        "test": "Test split (held out, frozen)",
        "dev": "Dev split (v2 was tuned on this)",
        "limits": "Known limitations (cases v2 is known to fail)",
    }
    for split in ("test", "dev", "limits"):
        examples = load_split(split)
        reports = [evaluate(cls(), examples, label) for _key, label, cls in ENGINES]
        title = titles[split]
        md += [f"## {title}", "", table(reports, len(examples)), ""]
        md += ["### Every miss and false positive", ""]
        md += [failures_md(r, split) for r in reports]
        results[split] = {
            key: {
                "recall": r.recall,
                "precision": r.precision,
                "f1": r.f1,
                "clean_rate": r.clean_rate,
                "by_type": r.by_type,
                "negatives": r.negatives,
                "negatives_clean": r.negatives_clean,
                "failures": [f.__dict__ for f in r.failures],
            }
            for (key, _label, _cls), r in zip(ENGINES, reports, strict=True)
        }
        print(f"\n== {title} ==\n")
        print(table(reports, len(examples)))

    (ROOT / "eval" / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    (ROOT / "eval" / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    if chart:
        draw_chart(results["test"])
    return results


def draw_chart(test: dict) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    labels = ["Recall", "Precision", "Clean negatives"]
    keys = ["recall", "precision", "clean_rate"]
    colors = ["#9aa5b1", "#5b8def", "#1f9d6b"]
    fig, ax = plt.subplots(figsize=(8, 4.2), dpi=150)
    width = 0.26
    for i, (key, label, _cls) in enumerate(ENGINES):
        values = [test[key][k] * 100 for k in keys]
        xs = [j + (i - 1) * width for j in range(len(keys))]
        bars = ax.bar(xs, values, width, label=label, color=colors[i])
        for bar, v in zip(bars, values, strict=True):
            ax.text(bar.get_x() + bar.get_width() / 2, v + 1.5, f"{v:.0f}", ha="center", fontsize=8)
    ax.set_xticks(range(len(keys)), labels)
    ax.set_ylim(0, 110)
    ax.set_ylabel("%")
    ax.set_title("Held-out test split: higher is better on every metric")
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.1), ncol=3)
    fig.tight_layout()
    out = ROOT / "docs" / "eval_chart.png"
    out.parent.mkdir(exist_ok=True)
    fig.savefig(out)
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--chart", action="store_true", help="also write docs/eval_chart.png")
    run(chart=parser.parse_args().chart)
